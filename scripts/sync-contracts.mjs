/**
 * Generate the frontend's contract bindings from Foundry's build output.
 *
 * ABIs are read from contracts/out and addresses from contracts/deployments,
 * so the UI can never drift from the contracts it talks to. Run after any
 * contract change or deployment:
 *
 *     make web-sync
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "contracts", "out");
const deployDir = join(root, "contracts", "deployments");
const target = join(root, "web", "src", "generated");

const CONTRACTS = [
  "ScoreOracle",
  "LendingPool",
  "RiskParams",
  "Guardian",
  "StaticPriceOracle",
  "FaucetToken",
];

function readAbi(name) {
  const file = join(outDir, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) {
    throw new Error(`missing artifact ${file}. Run \`make build\` first.`);
  }
  return JSON.parse(readFileSync(file, "utf8")).abi;
}

function readDeployments() {
  if (!existsSync(deployDir)) return {};
  const out = {};
  for (const file of readdirSync(deployDir)) {
    if (!file.endsWith(".json")) continue;
    const chainId = file.replace(".json", "");
    out[chainId] = JSON.parse(readFileSync(join(deployDir, file), "utf8"));
  }
  return out;
}

mkdirSync(target, { recursive: true });

const abis = Object.fromEntries(CONTRACTS.map((n) => [n, readAbi(n)]));
const banner = "// Generated by scripts/sync-contracts.mjs. Do not edit by hand.\n";

writeFileSync(
  join(target, "abis.ts"),
  banner +
    Object.entries(abis)
      .map(([name, abi]) => `export const ${name.toLowerCase()}Abi = ${JSON.stringify(abi)} as const;`)
      .join("\n\n") +
    "\n"
);

const deployments = readDeployments();
writeFileSync(
  join(target, "deployments.ts"),
  banner +
    "export type Deployment = {\n" +
    "  chainId: number;\n" +
    "  Guardian: `0x${string}`;\n" +
    "  RiskParams: `0x${string}`;\n" +
    "  ScoreOracle: `0x${string}`;\n" +
    "  StaticPriceOracle: `0x${string}`;\n" +
    "  LendingPool: `0x${string}`;\n" +
    "  collateralAsset: `0x${string}`;\n" +
    "  debtAsset: `0x${string}`;\n" +
    "  modelSigner: `0x${string}`;\n" +
    "  domainSeparator: `0x${string}`;\n" +
    "};\n\n" +
    `export const deployments: Record<number, Deployment> = ${JSON.stringify(
      Object.fromEntries(
        Object.entries(deployments).map(([id, d]) => [Number(id), { ...d, chainId: Number(id) }])
      ),
      null,
      2
    )} as const;\n`
);

const counts = Object.entries(abis).map(([n, a]) => `${n}(${a.length})`).join(" ");
console.log(`wrote web/src/generated/abis.ts       ${counts}`);
console.log(`wrote web/src/generated/deployments.ts chains: ${Object.keys(deployments).join(", ") || "none"}`);
